

// post increment
// Uses the current value then increases the value

let a = 4;
console.log(a++);
console.log(a);

let b = 17;
let d = b++;
console.log(d);
console.log(b);





// pre increment
// Increases the value first then uses new value

let x = 30;
console.log(++x);
console.log(x);

let y = 58;
let z = ++y;
console.log(z);
console.log(y);